import { Check, Copy } from 'lucide-react';
import { useEffect, useState } from 'react';
import { cn } from '@/lib/utils';
import { useI18n } from '@/i18n';
import { highlightJs } from '@/lib/highlight';

interface CodeBlockProps {
  code: string;
  label?: string;
  className?: string;
}

/** Read-only code block highlighted with Shiki (Abyss Reef theme). */
export const CodeBlock = ({ code, label, className }: CodeBlockProps) => {
  const { t } = useI18n();
  const [html, setHtml] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    let active = true;
    highlightJs(code)
      .then((result) => active && setHtml(result))
      .catch(() => active && setHtml(null));
    return () => {
      active = false;
    };
  }, [code]);

  async function copy() {
    try {
      await navigator.clipboard.writeText(code);
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    } catch {
      // no clipboard permission
    }
  }

  return (
    <figure
      className={cn(
        'relative overflow-hidden rounded-panel border-2 border-wood-deep bg-[var(--code-bg)] shadow-[0_8px_20px_-12px_rgb(0_0_0/0.7)]',
        className,
      )}
    >
      <figcaption className="wood flex items-center justify-between border-b border-wood-deep px-4 py-2 text-xs text-on-wood-muted">
        <span>{label ?? t('code.example')} · JavaScript</span>
        <button
          type="button"
          onClick={copy}
          className="inline-flex items-center gap-1 rounded-control px-2 py-1 hover:bg-black/20 hover:text-on-wood"
        >
          {copied ? <Check className="size-3.5" /> : <Copy className="size-3.5" />}
          {copied ? t('code.copied') : t('code.copy')}
        </button>
      </figcaption>
      {html ? (
        <div
          className="overflow-x-auto p-4 font-mono text-[0.8125rem] leading-relaxed [&_pre]:outline-none"
          // The HTML is generated by Shiki from content in this repo
          dangerouslySetInnerHTML={{ __html: html }}
        />
      ) : (
        <pre className="overflow-x-auto p-4 font-mono text-[0.8125rem] leading-relaxed">
          <code>{code}</code>
        </pre>
      )}
    </figure>
  );
};
